def count_words(text: str) -> int:
    return sum(1 for part in re.split(r"[^A-Za-z0-9]+", text) if part)


def is_license(text: str) -> bool:
    lowered = text.lower()
    return any(marker in lowered for marker in LICENSE_MARKERS)


def is_directive(text: str) -> bool:
    return bool(PROTECTED_RE.search(text)) or bool(DOCTEST_RE.search(text))


def ref_counts(text: str) -> tuple[int, int]:
    history = len(HISTORY_RE.findall(text)) + len(DATE_RE.findall(text))
    tickets = [match.group(0) for match in TICKET_RE.finditer(text)]
    tickets = [token for token in tickets if not TICKET_DENYLIST_RE.search(token)]
    return history, len(tickets)


def spec_for(path: str) -> CommentSpec | None:
    name = os.path.basename(path).lower()
    if name in FILENAME_SPECS:
        return FILENAME_SPECS[name]
    if name.endswith(".py") or name.endswith(".pyi"):
        return CommentSpec(("#",), ())
    return CODE_SPECS.get(os.path.splitext(name)[1])


def _scan_line(
    raw: str,
    spec: CommentSpec,
    open_block: str | None,
    base: int = 0,
    ranges: list[tuple[int, int]] | None = None,
    state: dict | None = None,
) -> tuple[str, str | None, bool, bool]:
    pieces: list[str] = []
    has_code = False
    touched = False
    i = 0
    n = len(raw)
    protected: list[tuple[int, int]] = []

    def mark(start: int, end: int) -> None:
        if ranges is not None:
            ranges.append((base + start, base + end))

    def skip_string(start: int, quote: str) -> int:
        j = start + 1
        while j < n:
            if raw[j] == "\\":
                j += 2
                continue
            if raw[j] == quote:
                return j + 1
            j += 1
        if state is not None:
            state["open_quote"] = quote
        return n

    open_quote = state.get("open_quote") if state is not None else None
    if open_quote:
        if state is not None:
            state["open_quote"] = None
        end = skip_string(-1, open_quote)
        protected.append((0, end))
        if state is not None and state.get("open_quote") == open_quote:
            return "", open_block, False, touched
        i = end

    if open_block is not None:
        touched = True
        idx = raw.find(open_block)
        if idx == -1:
            pieces.append(raw)
            mark(0, n)
            return " ".join(pieces), open_block, False, touched
        pieces.append(raw[:idx])
        i = idx + len(open_block)
        protected.append((0, i))
        mark(0, i)
        open_block = None

    while i < n:
        ch = raw[i]
        if ch in spec.quotes:
            end = skip_string(i, ch)
            protected.append((i, end))
            if state is not None and state.get("open_quote"):
                return " ".join(pieces), open_block, has_code, touched
            i = end
            continue
        matched = False
        for opener, closer in spec.block:
            if raw.startswith(opener, i) and not any(a <= i < b for a, b in protected):
                touched = True
                idx = raw.find(closer, i + len(opener))
                if idx == -1:
                    pieces.append(raw[i + len(opener):])
                    mark(i, n)
                    return " ".join(pieces), closer, has_code, touched
                pieces.append(raw[i + len(opener):idx])
                protected.append((i, idx + len(closer)))
                mark(i, idx + len(closer))
                i = idx + len(closer)
                matched = True
                break
        if matched:
            continue
        for marker in spec.line:
            if not raw.startswith(marker, i) or any(a <= i < b for a, b in protected):
                continue
            if marker == "#" and i > 0 and not raw[i - 1].isspace():
                continue
            touched = True
            pieces.append(raw[i + len(marker):])
            mark(i, n)
            i = n
            matched = True
            break
        if matched:
            continue
        if not ch.isspace():
            has_code = True
        i += 1

    return " ".join(p for p in pieces if p.strip()), open_block, has_code, touched


HEREDOC_RE = re.compile(r"<<([-~]?)\s*['\"]?([A-Za-z_][A-Za-z0-9_]*)['\"]?")
BLOCK_SCALAR_RE = re.compile(r"^\s*(?:[^\s#][^:]*:|-)\s*[|>][-+]?\d*\s*(?:#.*)?$")
DOLLAR_QUOTE_RE = re.compile(r"\$[A-Za-z_][A-Za-z0-9_]*\$|\$\$")


def _iter_lines(text: str, spec: CommentSpec):
    """Yield (line number, text) for lines that can hold code or comments.

    Heredoc bodies, block scalars, indented strings, and dollar-quoted bodies
    are data: a comment marker inside one is not a comment, and tightening it
    would change a program's input.
    """
    heredocs: list[tuple[str, bool]] = []
    scalar_indent: int | None = None
    nix_open = False
    dollar_open: str | None = None
    for number, raw in enumerate(text.split("\n"), 1):
        if number == 1 and raw.startswith("#!"):
            continue
        if heredocs:
            word, loose = heredocs[0]
            if raw == word or (loose and raw.lstrip() == word):
                heredocs.pop(0)
            continue
        if scalar_indent is not None:
            if raw.strip() and len(raw) - len(raw.lstrip()) <= scalar_indent:
                scalar_indent = None
            else:
                continue
        if nix_open:
            if raw.count("''") % 2 == 1:
                nix_open = False
            continue
        if dollar_open is not None:
            if dollar_open in raw:
                dollar_open = None
            continue
        opens_nix = spec.nix_string and raw.count("''") % 2 == 1
        tokens = DOLLAR_QUOTE_RE.findall(raw) if spec.dollar_quote else []
        if opens_nix or len(tokens) % 2 == 1:
            nix_open = opens_nix
            dollar_open = tokens[-1] if len(tokens) % 2 == 1 else None
            continue
        yield number, raw
        if spec.heredoc and not raw.lstrip().startswith("#"):
            heredocs.extend((match.group(2), bool(match.group(1)))
                            for match in HEREDOC_RE.finditer(raw))
        if spec.block_scalar and BLOCK_SCALAR_RE.match(raw):
            scalar_indent = len(raw) - len(raw.lstrip())


def scan_generic(text: str, spec: CommentSpec) -> tuple[list[list[tuple[int, str]]], int]:
    blocks: list[list[tuple[int, str]]] = []
    current: list[tuple[int, str]] = []
    open_block: str | None = None
    code_lines = 0

    def flush() -> None:
        nonlocal current
        if current:
            blocks.append(current)
            current = []

    state: dict = {}
    for number, raw in _iter_lines(text, spec):
        comment, open_block, has_code, touched = _scan_line(
            raw, spec, open_block, state=state)
        if has_code:
            code_lines += 1
        if touched:
            current.append((number, comment))
        else:
            flush()
    flush()
    return blocks, code_lines


def _drop_license_header(
    blocks: list[list[tuple[int, str]]]
) -> tuple[list[list[tuple[int, str]]], bool]:
    if not blocks:
        return blocks, False
    first = blocks[0]
    text = "\n".join(piece for _line, piece in first)
    if first[0][0] <= 2 and is_license(text):
        return blocks[1:], True
    return blocks, False


def _docstring_spans(tree: ast.AST) -> list[tuple[int, int, str]]:
    spans: list[tuple[int, int, str]] = []
    for node in ast.walk(tree):
        if not isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        body = getattr(node, "body", [])
        if body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant) \
                and isinstance(body[0].value.value, str):
            spans.append((body[0].lineno, getattr(body[0], "end_lineno", body[0].lineno),
                          body[0].value.value))
    spans.sort()
    return spans


def scan_python(text: str) -> tuple[list[list[tuple[int, str]]], int, bool, bool]:
    lines = text.split("\n")
    blocks: list[list[tuple[int, str]]] = []
    comment_lines: set[int] = set()
    try:
        tree = ast.parse(text)
    except SyntaxError:
        fallback, code_lines = scan_generic(text, CommentSpec(("#",), ()))
        fallback, license_header = _drop_license_header(fallback)
        return fallback, code_lines, license_header, False

    spans = _docstring_spans(tree)
    doc_lines = {line for start, end, _ in spans for line in range(start, end + 1)}
    try:
        for token in tokenize.generate_tokens(io.StringIO(text).readline):
            if token.type != tokenize.COMMENT:
                continue
            if token.start[0] == 1 and token.string.startswith("#!"):
                continue
            content = token.string.lstrip("#").strip()
            if not content:
                continue
            physical = lines[token.start[0] - 1]
            if physical[: token.start[1]].strip():
                blocks.append([(token.start[0], content)])
                continue
            comment_lines.add(token.start[0])
            if blocks and blocks[-1][-1][0] == token.start[0] - 1 \
                    and blocks[-1][-1][0] not in doc_lines:
                blocks[-1].append((token.start[0], content))
            else:
                blocks.append([(token.start[0], content)])
    except (tokenize.TokenError, IndentationError):
        fallback, code_lines = scan_generic(text, CommentSpec(("#",), ()))
        fallback, license_header = _drop_license_header(fallback)
        return fallback, code_lines, license_header, False

    for start, end, doc in spans:
        blocks.append([(line, doc if line == start else "") for line in range(start, end + 1)])
    comment_lines.update(doc_lines)
    if lines and lines[0].startswith("#!"):
        comment_lines.add(1)
    code_lines = sum(1 for number, line in enumerate(lines, 1)
                     if line.strip() and number not in comment_lines)
    blocks.sort(key=lambda block: block[0][0])
    blocks, license_header = _drop_license_header(blocks)
    return blocks, code_lines, license_header, True


def block_kind(text: str) -> str:
    if not text.strip():
        return ""
    if is_license(text):
        return "license"
    lines = [line for line in text.splitlines() if line.strip()]
    if any(DOCTEST_RE.match(line) for line in lines):
        return "doctest"
    if all(PROTECTED_RE.search(line) for line in lines):
        return "directive"
    return ""


def scan_code(
    text: str, language: str, spec: CommentSpec | None = None
) -> tuple[list[list[tuple[int, str]]], int, bool, bool]:
    if language in ("python", "py", "pyi"):
        return scan_python(text)
    if spec is None:
        spec = CODE_SPECS.get(language if language.startswith(".") else "." + language)
    if spec is None:
        return [], 0, False, True
    blocks, code_lines = scan_generic(text, spec)
    blocks, license_header = _drop_license_header(blocks)
    return blocks, code_lines, license_header, True


def _python_text_only(text: str) -> bool:
    lines = [line for line in text.splitlines() if line.strip()]
    if not lines or all(line.lstrip().startswith("#") for line in lines):
        return True
    try:
        tree = ast.parse(textwrap.dedent(text))
    except SyntaxError:
        return False
    return (len(tree.body) == 1 and isinstance(tree.body[0], ast.Expr)
            and isinstance(tree.body[0].value, ast.Constant)
            and isinstance(tree.body[0].value.value, str))


def is_commentary(text: str, path: str) -> bool:
    """True when a replacement fragment carries only comments or a docstring.

    The fragment must also leave nothing open: an unclosed block comment or
    string would swallow the code that follows it.
    """
    if path.lower().endswith((".py", ".pyi")):
        return _python_text_only(text)
    spec = spec_for(path)
    if spec is None:
        return False
    open_block = None
    state: dict = {}
    for line in text.splitlines():
        _comment, open_block, has_code, _touched = _scan_line(
            line, spec, open_block, state=state)
        if has_code or state.get("open_quote"):
            return False
    return open_block is None


def line_offsets(text: str) -> list[int]:
    offsets = [0]
    for match in re.finditer("\n", text):
        offsets.append(match.end())
    return offsets


def _offset(offsets: list[int], position: tuple[int, int]) -> int:
    row, column = position
    return offsets[row - 1] + column if row - 1 < len(offsets) else len(offsets) - 1


def _python_comment_ranges(text: str) -> tuple[list[tuple[int, int]], bool]:
    try:
        tree = ast.parse(text)
        tokens = list(tokenize.generate_tokens(io.StringIO(text).readline))
    except (SyntaxError, tokenize.TokenError, IndentationError):
        return [], False
    offsets = line_offsets(text)
    ranges: list[tuple[int, int]] = []
    strings = [token for token in tokens if token.type == tokenize.STRING]
    for start, end, _value in _docstring_spans(tree):
        for token in strings:
            if token.start[0] == start and token.end[0] == end:
                ranges.append((_offset(offsets, token.start), _offset(offsets, token.end)))
    for token in tokens:
        if token.type != tokenize.COMMENT:
            continue
        if token.start[0] == 1 and token.string.startswith("#!"):
            continue
        ranges.append((_offset(offsets, token.start), _offset(offsets, token.end)))
    return ranges, True


def comment_ranges(text: str, path: str) -> tuple[list[tuple[int, int]], bool]:
    """Character ranges covered by comments and docstrings; bool is "parsed"."""
    if path.lower().endswith((".py", ".pyi")):
        return _python_comment_ranges(text)
    spec = spec_for(path)
    if spec is None:
        return [], False
    offsets = line_offsets(text)
    ranges: list[tuple[int, int]] = []
    open_block = None
    state: dict = {}
    for number, raw in _iter_lines(text, spec):
        _comment, open_block, _code, _touched = _scan_line(
            raw, spec, open_block, base=offsets[number - 1], ranges=ranges, state=state)
    return ranges, True


STRUCTURAL_LINE_RE = re.compile(
    r"^\s*(?:[=\-~^\"'+#*_]{3,}|[^|\n]*\s\|\s[^|\n]*)\s*$")


def doc_protected_ranges(text: str) -> list[tuple[int, int]]:
    """Markdown regions that are code, data, or structure — never prose to cut."""
    offsets = line_offsets(text)
    lines = text.split("\n")
    ranges: list[tuple[int, int]] = []

    def span(first: int, last: int) -> tuple[int, int]:
        return offsets[first], offsets[min(last + 1, len(offsets) - 1)]

    start_line = 0
    if lines and lines[0].lstrip("﻿").strip() == "---":
        for index in range(1, len(lines)):
            if lines[index].strip() == "---":
                ranges.append(span(0, index))
                start_line = index + 1
                break

    fence_char = None
    fence_len = 0
    fence_start = 0
    in_comment = False
    comment_start = 0
    previous_blank = True
    in_list = False

    for index in range(start_line, len(lines)):
        raw = lines[index]
        stripped = raw.strip()
        match = re.match(r"^\s*(`{3,}|~{3,})", raw)

        if in_comment:
            if "-->" in stripped:
                in_comment = False
                ranges.append(span(comment_start, index))
            continue
        if fence_char is not None:
            if match and match.group(1)[0] == fence_char and len(match.group(1)) >= fence_len:
                ranges.append(span(fence_start, index))
                fence_char = None
            continue
        if match:
            fence_char, fence_len, fence_start = match.group(1)[0], len(match.group(1)), index
            continue
        if "<!--" in stripped and "-->" not in stripped:
            in_comment, comment_start = True, index
            continue
        if not stripped:
            previous_blank = True
            in_list = False
            continue
        if STRUCTURAL_LINE_RE.match(raw):
            ranges.append((offsets[index], offsets[index] + len(raw)))
            if index > start_line and lines[index - 1].strip() \
                    and not STRUCTURAL_LINE_RE.match(lines[index - 1]):
                ranges.append((offsets[index - 1], offsets[index - 1] + len(lines[index - 1])))
            continue
        if raw.startswith(("    ", "\t")) and not in_list and previous_blank:
            ranges.append((offsets[index], offsets[index] + len(raw)))
            continue
        in_list = bool(re.match(r"^\s*(?:[-*+]|\d+\.)\s", raw))
        previous_blank = False

    if fence_char is not None:
        ranges.append((offsets[fence_start], len(text)))
    if in_comment:
        ranges.append((offsets[comment_start], len(text)))
    for match in re.finditer(r"`[^`\n]+`|<[A-Za-z][^>]*>", text):
        ranges.append((match.start(), match.end()))
    return ranges


def rst_protected_ranges(text: str) -> list[tuple[int, int]]:
    """Directives and literal blocks, whose indented bodies are code or markup."""
    offsets = line_offsets(text)
    lines = text.split("\n")
    ranges: list[tuple[int, int]] = []
    index = 0
    while index < len(lines):
        raw = lines[index]
        stripped = raw.strip()
        if STRUCTURAL_LINE_RE.match(raw):
            ranges.append((offsets[index], offsets[index] + len(raw)))
            if index and lines[index - 1].strip() \
                    and not STRUCTURAL_LINE_RE.match(lines[index - 1]):
                ranges.append((offsets[index - 1], offsets[index - 1] + len(lines[index - 1])))
            index += 1
            continue
        opens = bool(re.match(r"^\.\.(\s|$)", stripped)) or (
            stripped.endswith("::") and not stripped.startswith(".."))
        if not opens:
            index += 1
            continue
        indent = len(raw) - len(raw.lstrip())
        last = index
        cursor = index + 1
        while cursor < len(lines):
            body = lines[cursor]
            if not body.strip():
                cursor += 1
                continue
            if len(body) - len(body.lstrip()) <= indent:
                break
            last = cursor
            cursor += 1
        ranges.append((offsets[index], offsets[min(last + 1, len(offsets) - 1)]))
        index = last + 1
    return ranges


def markdown_prose(text: str) -> tuple[int, int, int]:
    lines = text.split("\n")
    start = 0
    if lines and lines[0].lstrip("﻿").strip() == "---":
        for index in range(1, len(lines)):
            if lines[index].strip() == "---":
                start = index + 1
                break

    prose = 0
    total = 0
    headings = 0
    fence_char: str | None = None
    fence_len = 0
    in_comment = False
    previous_blank = True
    in_list = False

    for raw in lines[start:]:
        stripped = raw.strip()
        total += count_words(raw)

        fence_match = re.match(r"^\s*(`{3,}|~{3,})", raw)
        if fence_match:
            marker = fence_match.group(1)
            if fence_char is None:
                fence_char, fence_len = marker[0], len(marker)
            elif marker[0] == fence_char and len(marker) >= fence_len:
                fence_char, fence_len = None, 0
            previous_blank = False
            continue
        if fence_char:
            previous_blank = False
            continue

        if stripped.startswith("<!--"):
            in_comment = "-->" not in stripped
            previous_blank = False
            continue
        if in_comment:
            if "-->" in stripped:
                in_comment = False
            previous_blank = False
            continue

        if not stripped:
            previous_blank = True
            continue
        if raw.lstrip().startswith("#"):
            headings += 1
        if stripped.startswith("|") or re.match(r"^\s*\|?[\s:|-]+\|[\s:|-]*$", raw):
            previous_blank = False
            continue
        if raw.startswith(("    ", "\t")) and not in_list and previous_blank:
            previous_blank = False
            continue

        body = re.sub(r"^\s*#{1,6}\s*", "", raw)
        body = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", body)
        body = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", body)
        body = re.sub(r"\[([^\]]+)\]\[[^\]]*\]", r"\1", body)
        body = re.sub(r"`[^`]*`", "", body)
        body = re.sub(r"<?https?://\S+>?", "", body)
        body = re.sub(r"<[^>]+>", "", body)
        prose += count_words(body)
        in_list = bool(re.match(r"^\s*(?:[-*+]|\d+\.)\s", raw))
        previous_blank = False

    return prose, total, headings


def is_doc(path: str) -> bool:
    return os.path.splitext(path)[1].lower() in DOC_EXTENSIONS


def git_root(path: str) -> str | None:
    try:
        out = subprocess.run(["git", "-C", path, "rev-parse", "--show-toplevel"],
                             capture_output=True, text=True, check=True).stdout.strip()
        return out or None
    except (OSError, subprocess.CalledProcessError):
        return None


def line_ending(text: str) -> str:
    return "\r\n" if "\r\n" in text and text.count("\n") == text.count("\r\n") else "\n"


def normalize_newlines(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n")
